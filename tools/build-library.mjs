// Bundles programs/**/*.bas into js/c64/games.js (run: node tools/build-library.mjs)
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const load = (dir) => {
  const d = path.join(root, 'programs', dir);
  const order = fs.existsSync(path.join(d, 'ORDER')) ? fs.readFileSync(path.join(d, 'ORDER'), 'utf8').split('\n').map(s => s.trim()).filter(Boolean) : [];
  const files = fs.readdirSync(d).filter(f => f.endsWith('.bas'));
  const names = files.map(f => f.replace(/\.bas$/, ''));
  names.sort((a, b) => { const ia = order.indexOf(a), ib = order.indexOf(b); return (ia < 0 ? 999 : ia) - (ib < 0 ? 999 : ib) || a.localeCompare(b); });
  return names.map(n => ({ name: n, src: fs.readFileSync(path.join(d, n + '.bas'), 'utf8').replace(/\r\n?/g, '\n').trim() + '\n' }));
};
const games = load('games'), utils = load('utils');
const hash = crypto.createHash('sha1').update(JSON.stringify([games, utils])).digest('hex').slice(0, 8);
const out = `// GENERATED by tools/build-library.mjs from programs/*/*.bas. Edit the .bas files, not this file.
export const LIB_VERSION = ${JSON.stringify(hash)};
export const GAME_PROGRAMS = ${JSON.stringify(games, null, 1)};
export const UTILITY_PROGRAMS = ${JSON.stringify(utils, null, 1)};
`;
fs.writeFileSync(path.join(root, 'js/c64/games.js'), out);
console.log(`library: ${games.length} games, ${utils.length} utilities, version ${hash}`);
