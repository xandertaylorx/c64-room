function parseArt() {
  const g = {};
  for (const line of ART.trim().split('\n')) {
    const ch = [...line][0];
    const rows = line.slice(ch.length + 1).split('|');
    g[ch] = rows.map(r => {
      let b = 0;
      for (let i = 0; i < 8; i++) if (r[i] === '#') b |= 0x80 >> i;
      return b;
    });
  }
  return g;
}

// procedural helpers
const empty = () => [0, 0, 0, 0, 0, 0, 0, 0];
const fill = (fn) => { const g = empty(); for (let r = 0; r < 8; r++) for (let c = 0; c < 8; c++) if (fn(r, c)) g[r] |= 0x80 >> c; return g; };
const hl = (r0, h = 2) => fill((r) => r >= r0 && r < r0 + h);
const vl = (c0, w = 2) => fill((r, c) => c >= c0 && c < c0 + w);
const or = (...gs) => gs.reduce((a, b) => a.map((v, i) => v | b[i]), empty());
const CH = (r) => r === 3 || r === 4; // centre rows
const CV = (c) => c === 3 || c === 4; // centre cols
const checker = (r, c) => ((r + c) & 1) === 0;

function graphics(G) {
  // shared graphics for screen codes 64-127 in the upper/graphics set
  const s = {};
  s[64] = hl(3); s[65] = G['♠']; s[66] = vl(3); s[67] = hl(3); s[68] = hl(1); s[69] = hl(0);
  s[70] = hl(5); s[71] = vl(1); s[72] = vl(5); s[73] = G['╮']; s[74] = G['╰']; s[75] = G['╯'];
  s[76] = or(vl(0), hl(6)); s[77] = fill((r, c) => c === r || c === r - 1 || (r === 0 && c === 0));
  s[78] = fill((r, c) => c === 7 - r || c === 8 - r); s[79] = or(vl(0), hl(0)); s[80] = or(vl(6), hl(0));
  s[81] = G['●']; s[82] = hl(6); s[83] = G['♥']; s[84] = vl(0); s[85] = G['╭'];
  s[86] = or(s[77], s[78]); s[87] = G['○']; s[88] = G['♣']; s[89] = vl(6); s[90] = G['♦'];
  s[91] = fill((r, c) => CH(r) || CV(c)); s[92] = fill((r, c) => c < 4 && checker(r, c));
  s[93] = vl(3); s[94] = G['π']; s[95] = fill((r, c) => c >= r);
  s[96] = empty(); s[97] = vl(0, 4); s[98] = hl(4, 4); s[99] = hl(0, 1); s[100] = hl(7, 1);
  s[101] = vl(0, 1); s[102] = fill(checker); s[103] = vl(7, 1); s[104] = fill((r, c) => r >= 4 && checker(r, c));
  s[105] = fill((r, c) => c + r <= 7); s[106] = vl(6); s[107] = fill((r, c) => CV(c) || (CH(r) && c >= 3));
  s[108] = fill((r, c) => r >= 4 && c >= 4); s[109] = fill((r, c) => (CV(c) && r <= 4) || (CH(r) && c >= 3));
  s[110] = fill((r, c) => (CH(r) && c <= 4) || (CV(c) && r >= 3)); s[111] = hl(6);
  s[112] = fill((r, c) => (CH(r) && c >= 3) || (CV(c) && r >= 3)); s[113] = fill((r, c) => CH(r) || (CV(c) && r <= 4));
  s[114] = fill((r, c) => CH(r) || (CV(c) && r >= 3)); s[115] = fill((r, c) => CV(c) || (CH(r) && c <= 4));
  s[116] = vl(0); s[117] = vl(0, 3); s[118] = vl(5, 3); s[119] = hl(0); s[120] = hl(0, 3); s[121] = hl(5, 3);
  s[122] = or(vl(6), hl(6)); s[123] = fill((r, c) => r >= 4 && c < 4); s[124] = fill((r, c) => r < 4 && c >= 4);
  s[125] = fill((r, c) => (CH(r) && c <= 4) || (CV(c) && r <= 4)); s[126] = fill((r, c) => r < 4 && c < 4);
  s[127] = fill((r, c) => (r < 4) === (c < 4));
  return s;
}

export function buildCharRom() {
  const G = parseArt();
  const rom = new Uint8Array(4096);
  const put = (set, code, glyph) => {
    for (let i = 0; i < 8; i++) {
      rom[set * 2048 + code * 8 + i] = glyph[i];
      rom[set * 2048 + (code + 128) * 8 + i] = (~glyph[i]) & 0xff;
    }
  };
  const base = '@ABCDEFGHIJKLMNOPQRSTUVWXYZ[£]↑← !"#$%&\'()*+,-./0123456789:;<=>?';
  const lower = '@abcdefghijklmnopqrstuvwxyz';
  const gfx = graphics(G);
  const chars = [...base];
  for (let c = 0; c < 64; c++) {
    const g = chars[c] === ' ' ? empty() : G[chars[c]];
    put(0, c, g);
    const lc = c < 27 ? G[lower[c]] : g;
    put(1, c, lc);
  }
  for (let c = 64; c < 128; c++) put(0, c, gfx[c]);
  // lower/upper set: 64 = line, 65-90 uppercase, rest graphics
  for (let c = 64; c < 128; c++) {
    let g = gfx[c];
    if (c >= 65 && c <= 90) g = G[String.fromCharCode(c)];
    if (c === 94) g = fill(checker);
    if (c === 95) g = fill((r, cc) => ((r + cc) & 3) === 0 || ((r + cc) & 3) === 1);
    if (c === 122) g = G['✓'];
    put(1, c, g);
  }
  return rom;
}
